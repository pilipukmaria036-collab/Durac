package com.durak.game;

/** Поточна фаза ходу всередині одного раунду. */
public enum TurnPhase {
    /** Стіл порожній: атакуючий мусить покласти першу карту. */
    ATTACK,
    /** Захисник відбиває непобиті карти (або береться). */
    DEFEND,
    /** Атакуючі можуть підкинути карти того ж рангу, що вже лежать на столі, або сказати «бито/досить». */
    THROW_IN
}
